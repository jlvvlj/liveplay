// Turns Dexed's bundled cartridges (assets/builtin_pgm.zip, unzipped) into a
// C header of unpacked voices, the way Dexed's Cartridge::unpackProgram and
// Program::normalizePgmName read them.
//
// node cartridges.mjs <dir of .syx files> <out header>

import fs from 'node:fs';
import path from 'node:path';

const [dir, out] = process.argv.slice(2);

// Dexed_01 is the cartridge Dexed starts with; the SynprezFM ones follow in order
const files = fs
  .readdirSync(dir)
  .filter((f) => f.toLowerCase().endsWith('.syx'))
  .sort((a, b) => (a.startsWith('Dexed') === b.startsWith('Dexed') ? a.localeCompare(b) : a.startsWith('Dexed') ? -1 : 1));

const normparm = (value, max) => (value <= max ? value : Math.trunc((value / 255) * max));

function unpack(bulk) {
  const ret = new Uint8Array(156);
  for (let op = 0; op < 6; op++) {
    // Dexed computes normparm for these, then copies the raw bytes over them
    for (let i = 0; i < 11; i++) ret[op * 21 + i] = bulk[op * 17 + i];
    const leftrightcurves = bulk[op * 17 + 11] & 0xf;
    ret[op * 21 + 11] = leftrightcurves & 3;
    ret[op * 21 + 12] = (leftrightcurves >> 2) & 3;
    const detuneRs = bulk[op * 17 + 12] & 0x7f;
    ret[op * 21 + 13] = detuneRs & 7;
    const kvsAms = bulk[op * 17 + 13] & 0x1f;
    ret[op * 21 + 14] = kvsAms & 3;
    ret[op * 21 + 15] = (kvsAms >> 2) & 7;
    ret[op * 21 + 16] = bulk[op * 17 + 14] & 0x7f;
    const fcoarseMode = bulk[op * 17 + 15] & 0x3f;
    ret[op * 21 + 17] = fcoarseMode & 1;
    ret[op * 21 + 18] = (fcoarseMode >> 1) & 0x1f;
    ret[op * 21 + 19] = bulk[op * 17 + 16] & 0x7f;
    ret[op * 21 + 20] = (detuneRs >> 3) & 0x7f;
  }
  for (let i = 0; i < 8; i++) ret[126 + i] = normparm(bulk[102 + i] & 0x7f, 99);
  ret[134] = normparm(bulk[110] & 0x1f, 31);
  const oksFb = bulk[111] & 0xf;
  ret[135] = oksFb & 7;
  ret[136] = oksFb >> 3;
  ret[137] = bulk[112] & 0x7f;
  ret[138] = bulk[113] & 0x7f;
  ret[139] = bulk[114] & 0x7f;
  ret[140] = bulk[115] & 0x7f;
  const lpmsLfwLks = bulk[116] & 0x7f;
  ret[141] = lpmsLfwLks & 1;
  ret[142] = (lpmsLfwLks >> 1) & 7;
  ret[143] = lpmsLfwLks >> 4;
  ret[144] = bulk[117] & 0x7f;
  for (let i = 0; i < 10; i++) ret[145 + i] = bulk[118 + i] & 0x7f;
  // Every operator on, as Program() sets it
  ret[155] = 63;
  return ret;
}

function voiceName(bytes) {
  let name = '';
  for (let j = 0; j < 10; j++) {
    let c = bytes[j] & 0x7f;
    if (c === 92) c = 'Y'.charCodeAt(0);
    else if (c === 126) c = '>'.charCodeAt(0);
    else if (c === 127) c = '<'.charCodeAt(0);
    else if (c < 32 || c > 127) c = 32;
    name += String.fromCharCode(c);
  }
  return name.trim() || 'INIT VOICE';
}

const voices = [];
for (const file of files) {
  const data = fs.readFileSync(path.join(dir, file));
  // A 32-voice bulk dump: F0 43 0n 09 20 00, 4096 bytes, checksum, F7
  if (data.length < 4104 || data[0] !== 0xf0 || data[1] !== 0x43 || data[3] !== 0x09) {
    throw new Error(`${file} is not a DX7 32-voice cartridge`);
  }
  // Dexed reads the voices without checking the checksum; so does this
  const vmem = data.subarray(6, 6 + 4096);
  const cart = path.basename(file, path.extname(file));
  const label = cart.replace(/_/g, ' ');
  for (let i = 0; i < 32; i++) {
    const unpacked = unpack(vmem.subarray(i * 128, i * 128 + 128));
    voices.push({ id: `${cart}/${i + 1}`, name: `${voiceName(unpacked.subarray(145))} (${label})`, bytes: unpacked });
  }
}

const cString = (s) => JSON.stringify(s);
let text = `// Generated by cartridges.mjs from Dexed's assets/builtin_pgm.zip (${files.length} cartridges)\n`;
text += '#pragma once\n#include <cstdint>\n\n';
text += `static const int kCartridgeVoiceCount = ${voices.length};\n`;
text += `static const uint8_t kCartridgeVoices[${voices.length}][156] = {\n`;
for (const v of voices) text += `  {${Array.from(v.bytes).join(',')}},\n`;
text += '};\n';
text += `static const char* const kCartridgeIds[${voices.length}] = {\n`;
for (const v of voices) text += `  ${cString(v.id)},\n`;
text += '};\n';
text += `static const char* const kCartridgeNames[${voices.length}] = {\n`;
for (const v of voices) text += `  ${cString(v.name)},\n`;
text += '};\n';
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, text);
console.log(`${voices.length} voices from ${files.length} cartridges`);
