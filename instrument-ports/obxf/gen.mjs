// Generates, from the pinned OB-Xf sources, everything the port needs that
// upstream keeps behind JUCE:
//   SynthParam.h   upstream's parameter IDs and names, without the JUCE
//                  parameter classes that follow them
//   Utils.h        the two helpers the engine takes from upstream's Utils.h
//   obxf_data.h    the parameter list (ParameterList.h), the engine callback
//                  for each (ParameterCoordinator.h) and every factory patch
//
// node gen.mjs <OB-Xf dir> <output dir>
// Anything it cannot read stops the build.

import fs from 'node:fs';
import path from 'node:path';

const [src, out] = process.argv.slice(2);
if (!src || !out) {
  console.error('usage: node gen.mjs <OB-Xf dir> <output dir>');
  process.exit(2);
}
fs.mkdirSync(out, { recursive: true });
const read = (p) => fs.readFileSync(path.join(src, p), 'utf8');
const die = (message) => {
  console.error(`gen.mjs: ${message}`);
  process.exit(1);
};

// --- SynthParam.h: the ID and Name namespaces -----------------------------
const synthParam = read('src/parameter/SynthParam.h');
const nsStart = synthParam.indexOf('namespace SynthParam');
const nsEnd = synthParam.indexOf('} // namespace SynthParam');
if (nsStart < 0 || nsEnd < 0) die('SynthParam.h has no SynthParam namespace');
fs.writeFileSync(
  path.join(out, 'SynthParam.h'),
  '// Generated by gen.mjs from upstream src/parameter/SynthParam.h\n#pragma once\n#include <string>\n#include <Constants.h>\n\n' +
    synthParam.slice(nsStart, nsEnd) +
    '} // namespace SynthParam\n'
);
const namespaceBody = (name) => {
  const start = synthParam.indexOf(`namespace ${name}\n`);
  const end = synthParam.indexOf(`} // namespace ${name}`, start);
  if (start < 0 || end < 0) die(`SynthParam.h has no namespace ${name}`);
  const map = new Map();
  for (const m of synthParam.slice(start, end).matchAll(/static const std::string (\w+)\{"([^"]*)"\};/g)) {
    map.set(m[1], m[2]);
  }
  return map;
};
const ids = namespaceBody('ID');
const names = namespaceBody('Name');

// --- Utils.h ---------------------------------------------------------------
const utils = read('src/Utils.h');
const getPitch = utils.match(/^inline static float getPitch\(.*$/m);
if (!getPitch) die('Utils.h has no getPitch');
fs.writeFileSync(
  path.join(out, 'Utils.h'),
  '// Generated by gen.mjs: the engine helpers from upstream src/Utils.h\n#pragma once\n#include <cmath>\n#include <Constants.h>\n#include <engine/ParamScales.h>\n\n' +
    getPitch[0] +
    '\n'
);

// --- constants used in parameter ranges ------------------------------------
const config = read('src/configuration.h');
const constants = {};
for (const m of config.matchAll(/constexpr\s+\w+\s+(\w+)\{([^}]+)\};/g)) constants[m[1]] = m[2];
const evaluate = (expression) => {
  const text = expression
    .trim()
    .replace(/\b([A-Z_][A-Z0-9_]+)\b/g, (whole, name) => {
      if (!(name in constants)) die(`unknown constant ${name}`);
      return `(${constants[name]})`;
    })
    .replace(/(\d+\.?\d*)f\b/g, '$1')
    .replace(/(\d)\.(?!\d)/g, '$1.0');
  if (!/^[\d\s.+\-*/()]+$/.test(text)) die(`cannot evaluate ${expression}`);
  return Function(`return (${text});`)();
};

// --- ParameterList.h ---------------------------------------------------------
const list = read('src/parameter/ParameterList.h');
const listStart = list.indexOf('ParameterList{');
const listEnd = list.indexOf('};', listStart);
if (listStart < 0 || listEnd < 0) die('ParameterList.h has no ParameterList');
const body = list.slice(listStart + 'ParameterList{'.length, listEnd).replace(/\/\/[^\n]*/g, '');
const entries = [];
let depth = 0;
let begin = -1;
for (let i = 0; i < body.length; i++) {
  const c = body[i];
  if (c === '"') {
    i = body.indexOf('"', i + 1);
    continue;
  }
  if (c === '{') {
    if (depth === 0) begin = i;
    depth++;
  } else if (c === '}') {
    depth--;
    if (depth === 0) entries.push(body.slice(begin + 1, i));
  }
}

// The upstream prefab helpers, as parameter metadata
const prefabs = {
  'customPan()': { type: 'float', min: -1, max: 1, def: 0 },
  'customLFOWave(': { type: 'float', min: -1, max: 1, def: 0 },
  'tristateLFOTo()': { type: 'int', min: 0, max: 2, def: 0, options: ['Off', 'On', 'Inverted'] },
  'pmd()': { type: 'float', min: 0, max: 1, def: 0 },
};

const params = entries.map((entry) => {
  const idMatch = entry.match(/^\s*ID::(\w+)\s*,/);
  if (!idMatch) die(`no ID in parameter entry: ${entry.slice(0, 80)}`);
  const ident = idMatch[1];
  if (!ids.has(ident)) die(`ID::${ident} is not in SynthParam.h`);
  const rest = entry.slice(idMatch[0].length).trim();
  const prefab = Object.keys(prefabs).find((p) => rest.startsWith(p));
  if (!prefab) die(`${ident}: unknown parameter prefab in ${rest.slice(0, 40)}`);
  const p = { ...prefabs[prefab], ident, key: ids.get(ident) };
  if (p.options) p.options = [...p.options];
  // Every chained call, in order: their arguments hold no parentheses
  for (const m of rest.matchAll(/\.(\w+)\(([^()]*)\)/g)) {
    const [, method, args] = m;
    const parts = args.split(',').map((a) => a.trim());
    const clampDefault = (min, max) => {
      p.def = Math.min(Math.max(p.def, min), max);
    };
    switch (method) {
      case 'asFloat':
        p.type = 'float';
        break;
      case 'asInt':
        p.type = 'int';
        break;
      case 'asBool':
        p.type = 'bool';
        p.min = 0;
        p.max = 1;
        break;
      case 'asOnOffBool':
        p.type = 'bool';
        p.min = 0;
        p.max = 1;
        p.options = ['Off', 'On'];
        break;
      case 'withRange': {
        const [min, max] = parts.map(evaluate);
        clampDefault(p.min, p.max);
        p.min = min;
        p.max = max;
        break;
      }
      case 'withDefault':
        p.def = evaluate(parts[0]);
        break;
      case 'asPercent':
        clampDefault(p.min, p.max);
        p.min = 0;
        p.max = 1;
        p.def = 0;
        p.type = 'float';
        break;
      case 'asSemitoneRange':
        p.type = 'float';
        clampDefault(p.min, p.max);
        p.min = evaluate(parts[0]);
        p.max = evaluate(parts[1]);
        p.def = 0;
        break;
      case 'asCubicDecibelAttenuation':
        // asCubicDecibelUpTo(0): 0..1 with 1 as 0 dB, its default
        p.type = 'float';
        p.min = 0;
        p.max = 1;
        p.def = 1;
        break;
      case 'withName': {
        const n = args.match(/^Name::(\w+)$/);
        if (!n || !names.has(n[1])) die(`${ident}: unknown name ${args}`);
        p.label = names.get(n[1]);
        break;
      }
      case 'withGroupName':
        p.group = JSON.parse(args);
        break;
      default:
        break;
    }
  }
  const map = rest.match(/withUnorderedMapFormatting\(\{([\s\S]*?)\}\)/);
  if (map) {
    const options = [];
    for (const o of map[1].matchAll(/\{\s*(\d+)\s*,\s*"([^"]*)"\s*\}/g)) options[Number(o[1])] = o[2];
    if (options.length !== p.max - p.min + 1 || options.some((o) => o === undefined)) {
      die(`${ident}: its options do not cover ${p.min}..${p.max}`);
    }
    p.options = options;
  }
  if (p.type === 'bool' && !p.options) p.options = ['Off', 'On'];
  if (!p.label) die(`${ident}: no name`);
  if (!p.group) die(`${ident}: no group`);
  if (!(p.max > p.min)) die(`${ident}: empty range`);
  return p;
});

// --- engine callbacks ----------------------------------------------------------
const coordinator = read('src/parameter/ParameterCoordinator.h');
const handlers = new Map();
for (const m of coordinator.matchAll(/\{(\w+),\s*\[\]\(SynthEngine &s, float v\)\s*\{\s*(s\.\w+\([^;]*\));\s*\}\s*\}/g)) {
  handlers.set(m[1], m[2]);
}
for (const p of params) if (!handlers.has(p.ident)) die(`no engine callback for ${p.ident}`);

// --- factory patches -----------------------------------------------------------
const patchRoot = path.join(src, 'assets/installer/Surge Synth Team/OB-Xf/Patches');
const unescape = (s) =>
  s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const presets = [];
for (const category of fs.readdirSync(patchRoot).sort()) {
  const dir = path.join(patchRoot, category);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.fxp')) continue;
    const bytes = fs.readFileSync(path.join(dir, file));
    if (bytes.toString('latin1', 0, 4) !== 'CcnK' || bytes.toString('latin1', 8, 12) !== 'FPCh') {
      die(`${category}/${file} is not an OB-Xf program chunk`);
    }
    const chunkSize = bytes.readUInt32BE(56);
    const chunk = bytes.subarray(60, 60 + chunkSize);
    // JUCE's binary XML: 'VC2!', a little-endian length, then the text
    if (chunk.toString('latin1', 0, 4) !== 'VC2!') die(`${category}/${file}: no JUCE XML chunk`);
    const length = chunk.readUInt32LE(4);
    const xml = chunk.toString('utf8', 8, 8 + length);
    const root = xml.match(/<OB-Xf\s([^>]*?)\/?>/);
    if (!root) die(`${category}/${file}: no OB-Xf element`);
    const attributes = new Map();
    for (const a of root[1].matchAll(/([\w\-]+)="([^"]*)"/g)) attributes.set(a[1], unescape(a[2]));
    const version = attributes.get('ob-xf_version') || '';
    const versionNumber = /^\d{4}-\d{2}-\d{2}$/.test(version) ? parseInt(version.replace(/-/g, ''), 16) : 0;
    const maxVoices = evaluate('MAX_VOICES');
    const maxPannings = evaluate('MAX_PANNINGS');
    const values = params.map((p) => {
      const def = (p.def - p.min) / (p.max - p.min);
      let v = attributes.has(p.key) ? Number(attributes.get(p.key)) : def;
      if (!Number.isFinite(v)) die(`${category}/${file}: ${p.key} is not a number`);
      // StateManager::populateProgramFromXml's mapping for patches before 2025-12-13
      if (versionNumber < 0x20251213 && p.key === ids.get('UnisonVoices')) {
        const old = Math.min(Math.max(Math.round(v * (maxPannings - 1)), 0), maxPannings - 1);
        v = old / (maxVoices - 1);
      }
      return Math.fround(v);
    });
    const name = attributes.get('programName') || file.replace(/\.fxp$/, '');
    presets.push({ id: `${category}/${file.replace(/\.fxp$/, '')}`, name, tag: category, values });
  }
}
if (presets.length === 0) die('no factory patches found');

// --- obxf_data.h ---------------------------------------------------------------
const cString = (s) => JSON.stringify(s);
const cFloat = (v) => {
  const f = Math.fround(v);
  let s = Number.isInteger(f) ? `${f}.0` : String(f);
  if (!s.includes('e') && !s.includes('.')) s += '.0';
  return `${s}f`;
};
let h = `// Generated by gen.mjs from the pinned OB-Xf sources. Do not edit.
#pragma once

#include "SynthEngine.h"

namespace obxf_data
{
enum Kind { Float = 0, Int = 1, Choice = 2 };

struct ParamDef
{
    const char *key, *label, *group;
    float min, max, def;
    Kind kind;
    // A choice's option names, separated by '|'
    const char *options;
};

static constexpr int numParams = ${params.length};
static const ParamDef params[numParams] = {
`;
for (const p of params) {
  const kind = p.options ? 'Choice' : p.type === 'int' ? 'Int' : 'Float';
  h += `    {${cString(p.key)}, ${cString(p.label)}, ${cString(p.group)}, ${cFloat(p.min)}, ${cFloat(p.max)}, ${cFloat(p.def)}, ${kind}, ${cString((p.options || []).join('|'))}},\n`;
}
h += `};

// The engine callback upstream's ParameterCoordinator registers for each
// parameter; v is the normalized (0..1) value
inline void apply(SynthEngine &s, int index, float v)
{
    switch (index)
    {
`;
params.forEach((p, i) => {
  h += `    case ${i}: ${handlers.get(p.ident)}; break;\n`;
});
h += `    default: break;
    }
}

struct PresetDef
{
    const char *id, *name, *tag;
};

static constexpr int numPresets = ${presets.length};
static const PresetDef presets[numPresets] = {
`;
for (const p of presets) h += `    {${cString(p.id)}, ${cString(p.name)}, ${cString(p.tag)}},\n`;
h += `};

// Normalized values of every parameter, per preset
static const float presetValues[numPresets][numParams] = {
`;
for (const p of presets) h += `    {${p.values.map(cFloat).join(',')}},\n`;
h += `};
} // namespace obxf_data
`;
fs.writeFileSync(path.join(out, 'obxf_data.h'), h);
console.log(`gen.mjs: ${params.length} parameters, ${presets.length} factory patches`);
